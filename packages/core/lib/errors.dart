/// Ошибка, которую можно показать человеку как есть.
///
/// Большинство сбоев — «нет связи», «база не открылась» — человеку ни о
/// чём не говорят, и экран заменяет их общим «что-то пошло не так». Но
/// бывают отказы по правилам: «примите правила», «карта отклонена». Их
/// текст и есть объяснение, и заменять его нельзя.
///
/// Общий предок нужен, чтобы экран и сервер узнавали такие ошибки одной
/// проверкой, а не перечисляли каждую поимённо.
class UserError implements Exception {
  final String message;

  const UserError(this.message);

  @override
  String toString() => message;
}
