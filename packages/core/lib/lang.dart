// Языки приложения: казахский, русский, английский.
//
// Язык — это не только перевод надписей. От него зависят окончания после
// чисел («2 смены», «2 ауысым», «2 shifts»), названия месяцев, порядок
// слов в дате. Поэтому всё, что зависит от языка, собрано в словарях
// (`l10n/`), а здесь — только сам выбор.

/// Язык интерфейса.
enum Lang {
  kk('kk', 'Қазақша'),
  ru('ru', 'Русский'),
  en('en', 'English');

  /// Двухбуквенный код — как в стандарте ISO 639 и в заголовке
  /// `Accept-Language`, который приложение шлёт серверу.
  final String code;

  /// Название языка на нём самом: в списке выбора человек ищет «Қазақша»,
  /// а не «казахский».
  final String selfName;

  const Lang(this.code, this.selfName);

  /// Язык по коду. Незнакомый код — русский: на нём написано приложение,
  /// и на нём его точно поймут в Казахстане.
  static Lang fromCode(String? code) {
    final short = (code ?? '').trim().toLowerCase();
    for (final lang in values) {
      if (short.startsWith(lang.code)) return lang;
    }
    return ru;
  }

  /// Язык из заголовка `Accept-Language: kk-KZ,kk;q=0.9,ru;q=0.8`.
  /// Берём первый, который знаем.
  static Lang fromHeader(String? header) {
    if (header == null || header.isEmpty) return ru;
    for (final part in header.split(',')) {
      final code = part.split(';').first.trim().toLowerCase();
      for (final lang in values) {
        if (code.startsWith(lang.code)) return lang;
      }
    }
    return ru;
  }
}

/// Язык, на котором приложение сейчас говорит с человеком.
///
/// Глобальная переменная — сознательно. Язык один на весь экран, и
/// протаскивать его параметром через каждую функцию форматирования
/// («12 сентября», «2 смены») значило бы переписать половину кода ради
/// одного значения. На телефоне его ставит приложение при запуске и при
/// смене языка в профиле.
///
/// Сервер этой переменной не пользуется: он говорит со многими людьми
/// сразу, и у каждого свой язык. Там словарь передают явно — см.
/// `CoreStrings.of`.
Lang appLang = Lang.ru;
