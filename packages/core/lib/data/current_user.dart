import '../user.dart';

/// Кто сейчас действует.
///
/// Хранилищу нужно знать про действующего лишь четыре вещи: кто он, какой
/// у него рейтинг и город. Больше ничего.
///
/// Раньше хранилище принимало `AppSession` целиком — а она умеет сообщать
/// экранам об изменениях и ради этого наследуется от Flutter. Получалось,
/// что SQL-запросы тянули за собой всю мобильную библиотеку, и сервер их
/// просто не мог запустить.
///
/// Теперь хранилище просит не конкретный класс, а **это описание**.
/// В приложении его выполняет `AppSession`, на сервере — объект с автором
/// запроса. Тот же приём, что и с самими репозиториями: просим умение,
/// а не исполнителя.
abstract class CurrentUser {
  AppUser? get user;

  /// Номер текущего пользователя. 0 — никого нет.
  int get workerId;

  /// Рейтинг — по нему решается допуск к сменам.
  double get rating;

  /// Город — по нему фильтруется лента.
  String get city;
}

/// Простая реализация: просто держит пользователя и ничего не сообщает.
/// Для сервера, где «сессия» живёт ровно один запрос.
class StaticUser implements CurrentUser {
  @override
  final AppUser? user;

  const StaticUser(this.user);

  @override
  int get workerId => user?.id ?? 0;

  @override
  double get rating => user?.rating ?? 0;

  @override
  String get city => user?.city ?? '';
}
