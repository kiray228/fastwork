// Правила сервиса — то, с чем человек соглашается при регистрации.
//
// Текст лежит в ядре, а не на экране: его показывает приложение, а версию
// проверяет сервер. Версия — главное. Поправили правила по существу —
// подняли номер, и каждый, кто соглашался со старыми, при следующем входе
// увидит новые и согласится заново. Молча подменить текст, под которым
// человек уже подписался, было бы нечестно.

import 'l10n/core_strings.dart';

/// Версия правил. Поднимается, когда меняются условия.
const kTermsVersion = 1;

/// Один раздел правил.
class TermsSection {
  final String title;
  final String body;

  const TermsSection(this.title, this.body);
}

/// Заголовок правил — на языке приложения.
///
/// Текст правил переведён на казахский и английский, но смысл у всех трёх
/// один: версия (`kTermsVersion`) общая, и согласие на любом языке — это
/// согласие с одними и теми же условиями.
String get kTermsTitle => coreTr.termsTitle;

/// Разделы правил — на языке приложения.
List<TermsSection> get kTermsSections => coreTr.termsSections;
